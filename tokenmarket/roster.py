"""v1.0 programmatic seller roster (protocol §2: >= 40 sellers, >= 30 honest, >= 3 strategic, 3 attack types).

A config with a top-level `roster:` block gets its `sellers:` list generated by `materialize(cfg, run_seed)`.
The roster depends only on roster.seed (fixed across runs) unless roster.resample_per_seed is true, in which case
it is redrawn per run seed from (roster.seed, run seed) - recommended for T4, where a fixed roster lets a model
memorise which (price, model, jurisdiction) combination attacks.

Seller ids are s00..sNN in a shuffled order, so an id does not reveal whether a seller is strategic. Configs
without `roster:` are returned unchanged (v0.1 behaviour).
"""
from __future__ import annotations

import copy
import random
from typing import Dict, List, Optional

DEFAULT_JURISDICTIONS = {
    "CN": {"latency_mean_ms": 150, "latency_std_ms": 60},
    "SG": {"latency_mean_ms": 100, "latency_std_ms": 40},
    "BR": {"latency_mean_ms": 400, "latency_std_ms": 120},
}
DEFAULT_FLAGS = {"cn_standard_contract": 0.5, "br_scc": 0.5, "sg_contractual_safeguards": 0.5,
                 "cn_security_assessment": 0.15}


def roster_seed(spec: Dict, run_seed: Optional[int] = None) -> str:
    base = spec.get("seed", 20261110)
    if spec.get("resample_per_seed") and run_seed is not None:
        return f"roster-{base}-run{int(run_seed)}"
    return f"roster-{base}"


def _u(rng: random.Random, lo_hi) -> float:
    lo, hi = (float(lo_hi), float(lo_hi)) if not isinstance(lo_hi, (list, tuple)) else map(float, lo_hi)
    return rng.uniform(lo, hi)


def _seller(rng, sid, juris, jcfg, flags_p, cap, model_cfg) -> Dict:
    jit = float(jcfg.get("jitter", 0.2))
    lm = float(jcfg["latency_mean_ms"]) * rng.uniform(1 - jit, 1 + jit)
    ls = float(jcfg["latency_std_ms"]) * rng.uniform(1 - jit, 1 + jit)
    flags = [f for f, p in sorted(flags_p.items()) if rng.random() < float(p)]
    return {"id": sid, "jurisdiction": juris, "backend": model_cfg.get("backend", "mock"),
            "latency": {"mean_ms": round(lm, 1), "std_ms": round(ls, 1)},
            "capacity_per_round": int(cap), "flags": flags}


def generate_roster(spec: Dict, seed_str: str) -> List[Dict]:
    rng = random.Random(seed_str)
    juris = spec.get("jurisdictions", DEFAULT_JURISDICTIONS)
    jnames = sorted(juris)
    flags_p = spec.get("flags", DEFAULT_FLAGS)
    cap = int(spec.get("capacity_per_round", 20))
    honest = spec["honest_models"]
    weights = [float(h.get("weight", 1.0)) for h in honest]
    st = spec["strategic"]
    groups = st["groups"]               # [{attack_modes: [...], count: n}, ...]
    n_honest = int(spec["n_honest"])
    n_strat = sum(int(g["count"]) for g in groups)
    n = n_honest + n_strat
    ids = [f"s{i:02d}" for i in range(n)]
    rng.shuffle(ids)
    out = []
    for k in range(n_honest):
        h = rng.choices(honest, weights=weights, k=1)[0]
        j = rng.choice(jnames)
        s = _seller(rng, ids[k], j, juris[j], flags_p, cap, h)
        price = _u(rng, h["price_per_1k"])
        s.update(claimed_model=h["model"], actual_model=h["model"], price_per_1k=round(price, 4),
                 cost_per_1k=round(price * _u(rng, h.get("cost_ratio", [0.5, 0.7])), 4))
        out.append(s)
    k = n_honest
    for g in groups:
        for _ in range(int(g["count"])):
            j = rng.choice(jnames)
            s = _seller(rng, ids[k], j, juris[j], flags_p, cap, st)
            s.update(claimed_model=st["claimed_model"], actual_model=st["cheap_model"],
                     price_per_1k=round(_u(rng, st["price_per_1k"]), 4), cost_per_1k=float(st["cheap_cost_per_1k"]),
                     strategy={"honest_model": st["claimed_model"],
                               "honest_cost_per_1k": float(st["honest_cost_per_1k"]),
                               "attack_modes": list(g["attack_modes"])})
            if "downgrade_min_difficulty" in g:
                s["strategy"]["downgrade_min_difficulty"] = int(g["downgrade_min_difficulty"])
            out.append(s)
            k += 1
    out.sort(key=lambda s: s["id"])
    return out


def materialize(cfg: Dict, run_seed: Optional[int] = None) -> Dict:
    """Return cfg with `sellers` generated from `roster` (cfg unchanged if it has no roster block)."""
    spec = cfg.get("roster")
    if not spec:
        return cfg
    out = copy.deepcopy(cfg)
    out["sellers"] = generate_roster(spec, roster_seed(spec, run_seed))
    return out


def strategic_ids(cfg: Dict) -> List[str]:
    return [s["id"] for s in cfg["sellers"] if s["claimed_model"] != s["actual_model"]]
