#!/usr/bin/env python3
"""Render only the adopted 9072b0d CSV; never recompute or rescale prices."""

import csv
import hashlib
import io
from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parents[1]
READOUT = Path("results/v1.1/v1.2_price_representativeness/ratios.csv")
COMMIT = "9072b0d71e92c1cf15916abce9d7f9f2a4959e2d"
OUTPUT = ROOT / "docs/latex-sigkdd-v1.0/tables/price_ratios.tex"
PRIMARY = {
    ("roster:midpoint", "1.5B/0.5B"): "2.05",
    ("roster:midpoint", "1.5B/mock"): "3.153846154",
    ("roster:midpoint", "0.5B/mock"): "1.538461538",
    ("public:openai", "output_max/output_min"): "40",
    ("public:openai", "input_max/input_min"): "50",
    ("public:anthropic", "output_max/output_min"): "80",
    ("public:anthropic", "input_max/input_min"): "80",
    ("public:google", "output_max/output_min"): "1.2",
    ("public:google", "input_max/input_min"): "1",
    ("public:pool", "output_max/output_min"): "100",
    ("public:pool", "input_max/input_min"): "100",
}


def render():
    data = (ROOT / READOUT).read_bytes()
    official = subprocess.check_output(
        ["git", "--no-pager", "show", f"{COMMIT}:{READOUT.as_posix()}"],
        cwd=ROOT,
    )
    if data != official:
        raise SystemExit("STOP: ratios.csv differs from the adopted 9072b0d readout")
    rows = list(csv.DictReader(io.StringIO(data.decode())))
    indexed = {}
    for row in rows:
        indexed.setdefault((row["scope"], row["metric"]), []).append(row)

    def row(scope, metric):
        matches = indexed[(scope, metric)]
        if len(matches) != 1:
            raise SystemExit(f"STOP: expected one row for {scope}, {metric}")
        return matches[0]

    def value(scope, metric):
        return row(scope, metric)["value"]

    for key, expected in PRIMARY.items():
        if value(*key) != expected:
            raise SystemExit(f"STOP: primary figure differs: {key}")
    for metric in ("prices_yaml_sha256", "scale_yaml_sha256"):
        source = row("source", metric)
        actual = hashlib.sha256((ROOT / source["numerator"]).read_bytes()).hexdigest()
        if actual != source["value"]:
            raise SystemExit(f"STOP: frozen input hash differs: {source['numerator']}")

    lines = [
        "% Generated by scripts/pass16_price_ratio_tables.py; do not hand-edit.",
        f"% Source: {READOUT.as_posix()} at {COMMIT}",
        f"% CSV sha256: {hashlib.sha256(data).hexdigest()}",
        r"\begin{table}[!htbp]",
        r"\caption{Descriptive price-ratio comparison only, not calibration or",
        r"production-market validation; not applied to official runs.",
        r"Panels use internal spreads in different units, not USD price-level",
        r"comparisons or mappings of Qwen/mock/strategic sellers to public SKUs.",
        r"Simulator \mbox{\protect\code{price_per_1k}} has no input/output split.",
        r"No marketplace logs support quantitative latency, volume,",
        r"jurisdiction, or executed-trade comparisons.",
        r"Snapshot access: 2026-11-10; Google has only two filled models,",
        r"excluding unverified \protect\code{gemini-3.1-flash-lite}.",
        r"DeepSeek and Alibaba were empty.",
        r"Decision A / Result 1 tables and numbers are unchanged.}",
        r"\label{tab:price-ratios}",
        r"\small",
        r"\begin{tabular}{@{}lr@{}}",
        r"\toprule",
        r"\multicolumn{2}{@{}l}{Synthetic roster: honest midpoint ratios} \\",
        r"\midrule",
    ]
    for metric in ("1.5B/0.5B", "1.5B/mock", "0.5B/mock"):
        lines.append(f"{metric} & {value('roster:midpoint', metric)} " + r"\\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\smallskip",
        r"\begin{tabular}{@{}lrrr@{}}",
        r"\toprule",
        r"Public list & Filled & Output spread & Input spread \\",
        r"\midrule",
    ]
    for provider, label in (
        ("openai", "OpenAI"),
        ("anthropic", "Anthropic"),
        ("google", "Google"),
        ("pool", "Three-provider pool"),
    ):
        scope = f"public:{provider}"
        output = row(scope, "output_max/output_min")
        count = re.search(r"\bn=(\d+)\b", output["notes"]).group(1)
        lines.append(
            f"{label} & {count} & {output['value']} & "
            f"{value(scope, 'input_max/input_min')} " + r"\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\smallskip",
        r"\begin{minipage}{\columnwidth}\footnotesize",
        r"Exact CSV values are printed without rounding. Midpoints use",
        r"$(\mathrm{lo}+\mathrm{hi})/2$; public spreads are",
        r"$\mathrm{output}_{\max}/\mathrm{output}_{\min}$ and",
        r"$\mathrm{input}_{\max}/\mathrm{input}_{\min}$, computed separately.",
        r"The pool comprises OpenAI, Anthropic, and Google.",
        r"\end{minipage}",
        r"\end{table}",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()  # All guards pass before any output is written.
    OUTPUT.write_text(text)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} from the verified official CSV.")
