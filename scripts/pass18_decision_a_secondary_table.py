#!/usr/bin/env python3
"""Generate Appendix secondary accuracy & cost_per_task tables verbatim from official Decision A cells.csv.

Follows docs/PROTOCOL_T5.md §10: copies existing official accuracy and cost_per_task
mean/lo/hi values from results/v1.1/v1.2_decision_a_eval/cells.csv without recomputation.
Does not touch v1.0 main/per_seed.csv and is not used for main-text ranking.
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "results/v1.1/v1.2_decision_a_eval"
OUT = ROOT / "docs/latex-sigkdd-v1.0/tables/decision_a_acc_cost.tex"
LEARNERS = ("egreedy", "fictitious_play", "exp3")
ROUTERS = (("pilot", "PILOT"), ("strongest", "strongest"))
AUDITS = ("a0", "a0.01", "a0.02", "a0.03", "a0.05", "a0.1", "a0.2", "risk_adaptive")
PENALTIES = (
    (0.25, "P=0.25", "p025", "default $P=0.25$"),
    (0.0625, "P/4=0.0625", "p4", "lower penalty $P/4=0.0625$"),
    (0.015625, "P/16=0.015625", "p16", "lower penalty $P/16=0.015625$"),
)


def audit_label(audit: str) -> str:
    if audit == "risk_adaptive":
        return "risk-adaptive"
    value = float(audit[1:])
    return "0 (ref.)" if value == 0 else f"{value:.2f}"


def fmt_ci(raw_json: str, places: int) -> str:
    d = json.loads(raw_json)
    m = f"{d['mean']:.{places}f}"
    lo = f"{d['lo']:.{places}f}"
    hi = f"{d['hi']:.{places}f}"
    return rf"\cil{{{m}}}{{{lo}}}{{{hi}}}"


def main() -> int:
    # Verify official cells.csv sha256 before reading.
    digest, filename = (SOURCE / "cells.csv.sha256").read_text(encoding="utf-8").split()
    assert filename == "cells.csv", filename
    actual = hashlib.sha256((SOURCE / "cells.csv").read_bytes()).hexdigest()
    assert actual == digest, f"cells.csv sha256 mismatch: {actual} != {digest}"

    with (SOURCE / "cells.csv").open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    assert len(rows) == 144, f"expected 144 rows, got {len(rows)}"

    lines = [
        "% Generated by scripts/pass18_decision_a_secondary_table.py from results/v1.1/v1.2_decision_a_eval/cells.csv; do not edit.",
    ]
    for pen_val, pen_short, pen_slug, pen_desc in PENALTIES:
        cell_map = {
            (r["router"], r["audit"], r["learner"]): r
            for r in rows
            if float(r["penalty"]) == pen_val
        }
        assert len(cell_map) == 48, f"expected 48 rows for penalty {pen_val}, got {len(cell_map)}"
        lines += [
            r"\begin{table*}[p]",
            (
                r"\caption{Decision A secondary \texttt{accuracy} and \texttt{cost\_per\_task} intervals ("
                + pen_desc
                + r", $\pi=1$, 1000 rounds, 20 seeds; mean [95\% CI]). Copied verbatim from existing official "
                r"\texttt{results/v1.1/v1.2\_decision\_a\_eval/cells.csv} (not recomputed). "
                r"Not used for main-text ranking and does not modify any Decision A $\Emet$/$\Qmet$ conclusion.}"
            ),
            rf"\label{{tab:decision-a-acccost-{pen_slug}}}",
            r"\centering\scriptsize",
            r"\setlength{\tabcolsep}{2.6pt}",
            r"\renewcommand{\arraystretch}{0.92}",
            r"\begin{tabular}{@{}llcccccc@{}}",
            r"\toprule",
            r"Router & Audit $a$ & \multicolumn{2}{c}{egreedy} & \multicolumn{2}{c}{fictitious play} & \multicolumn{2}{c}{EXP3} \\",
            r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(l){7-8}",
            r"& & accuracy & cost/task & accuracy & cost/task & accuracy & cost/task \\",
            r"\midrule",
        ]
        for idx, (rkey, rname) in enumerate(ROUTERS):
            if idx > 0:
                lines.append(r"\midrule")
            for audit in AUDITS:
                row_cells = [rname, audit_label(audit)]
                for learner in LEARNERS:
                    c = cell_map[rkey, audit, learner]
                    row_cells.append(fmt_ci(c["accuracy"], 4))
                    row_cells.append(fmt_ci(c["cost_per_task"], 5))
                lines.append(" & ".join(row_cells) + r" \\")
        lines += [
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table*}",
        ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} (144 cells verbatim from cells.csv; sha256 verified {actual})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
